"""Build the rerunnable Supabase migration from the validated answer key."""

import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
key = json.loads((ROOT / "assets/answer-key.json").read_text())
if len(key["answers"]) != 500:
    raise ValueError("Expected 500 answers")

header = """-- Generated by scripts/build-answer-migration.py from assets/answer-key.json.
-- Run as administrator in the linked Supabase project's SQL Editor.
begin;

create table if not exists public.quiz_answers (
  problem_key text primary key check (
    problem_key ~ '^(201[6-9]|202[0-5])-AMC10[AB]-([1-9]|1[0-9]|2[0-5])$'
  ),
  answer text not null check (answer in ('A', 'B', 'C', 'D', 'E')),
  source_url text not null
);
alter table public.quiz_answers enable row level security;
revoke all on public.quiz_answers from public, anon, authenticated;

insert into public.quiz_answers (problem_key, answer, source_url) values
"""
rows = []
for problem_key, answer in key["answers"].items():
    match = re.fullmatch(r"(201[6-9]|202[0-5])-AMC10([AB])-([1-9]|1[0-9]|2[0-5])", problem_key)
    if not match or answer not in "ABCDE" or len(answer) != 1:
        raise ValueError("Invalid answer entry")
    paper = match[1] + match[2]
    source = key["sources"][paper]
    if source != f"https://live.poshenloh.com/past-contests/amc10/{paper}":
        raise ValueError("Unexpected source")
    rows.append(f"  ('{problem_key}', '{answer}', '{source}/answers')")

footer = """
on conflict (problem_key) do update set
  answer = excluded.answer, source_url = excluded.source_url;

create or replace function public.check_quiz_answer(
  p_expected_user uuid, p_problem_key text, p_answer text
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  correct_answer text;
begin
  if auth.uid() is null or auth.uid() is distinct from p_expected_user then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if p_answer is null or p_answer not in ('A', 'B', 'C', 'D', 'E')
    or p_problem_key is null
    or p_problem_key !~ '^(201[6-9]|202[0-5])-AMC10[AB]-([1-9]|1[0-9]|2[0-5])$' then
    raise exception 'Invalid quiz answer' using errcode = '22023';
  end if;
  select answer into correct_answer from public.quiz_answers
    where problem_key = p_problem_key;
  if not found then
    raise exception 'Answer key entry missing' using errcode = 'P0002';
  end if;
  return jsonb_build_object(
    'problem_key', p_problem_key, 'correct', p_answer = correct_answer
  );
end;
$$;
revoke all on function public.check_quiz_answer(uuid, text, text) from public, anon, authenticated;
grant execute on function public.check_quiz_answer(uuid, text, text) to authenticated;
notify pgrst, 'reload schema';
commit;
"""
(ROOT / "supabase/add-quest-answers.sql").write_text(header + ",\n".join(rows) + "\n" + footer)
